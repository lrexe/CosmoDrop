"""Тексты бота-хранителя: понятные инструкции для новичков (/start, /deposit, /withdraw, /rules, /help)."""

COMMANDS = [
    {"command": "start", "description": "Как это работает"},
    {"command": "deposit", "description": "Как внести подарок"},
    {"command": "withdraw", "description": "Как забрать подарок обратно"},
    {"command": "rules", "description": "Что принимается и сколько стоит"},
    {"command": "help", "description": "Вся справка"},
]
SHORT_DESC = "Хранитель подарков Vloody: принимает NFT-подарки и выдаёт их победителям."
LONG_DESC = ("Я — хранитель подарков Vloody. Подарки лежат у меня, пока идёт розыгрыш, и уходят "
             "победителю автоматически. Нажми /start — расскажу, как внести подарок и как его забрать.")
SEP = "\n\n— — —\n\n"


def keeper_ref(owner_username):
    return f"@{owner_username}" if owner_username else "аккаунт-хранитель (его имя покажет приложение Vloody)"


def text_start(owner):
    return (
        "👋 Привет! Я — хранитель подарков Vloody.\n\n"
        "Подарки в розыгрышах не «исчезают» и не принадлежат платформе: пока идёт раунд, "
        "они лежат у меня, а победителю уходят автоматически.\n\n"
        "Как начать за минуту:\n"
        f"1️⃣ Открой чат с {keeper_ref(owner)} → 🎁 Подарок → выбери свой уникальный (NFT) подарок и отправь.\n"
        "2️⃣ Подожди ~15 секунд — подарок появится в «Профиль → Инвентарь» в приложении Vloody.\n"
        "3️⃣ Выставь его в розыгрыш или оставь в инвентаре.\n\n"
        "Команды: /deposit · /withdraw · /rules · /help"
    )


def text_deposit(owner):
    return (
        "📥 Как внести подарок\n\n"
        f"1. Открой чат с {keeper_ref(owner)}.\n"
        "2. Нажми 📎 → «Подарок» (или значок 🎁 в профиле получателя).\n"
        "3. Выбери СВОЙ уникальный NFT-подарок и отправь. Не скрывай отправителя — "
        "иначе я не пойму, чей это подарок.\n"
        "4. Через ~15 секунд я напишу сюда «✅ принят», а подарок появится в инвентаре Vloody.\n\n"
        "⚠️ Отправляй подарок с того Telegram-аккаунта, под которым ты входишь в Vloody."
    )


def text_withdraw():
    return (
        "📤 Как забрать подарок\n\n"
        "1. Открой Vloody → Профиль → Инвентарь.\n"
        "2. Нажми на подарок → «Вывести».\n"
        "3. Подтверди — через несколько секунд я передам подарок тебе в Telegram и напишу «🎁 отправлен».\n\n"
        "Telegram берёт плату за передачу подарка — приложение покажет её перед подтверждением. "
        "Если передача не удалась, подарок вернётся в инвентарь, а плата — на баланс."
    )


def text_rules():
    return (
        "📜 Правила и честность\n\n"
        "• Принимаются только уникальные (NFT) подарки. Обычные подарки за звёзды не принимаются.\n"
        "• Раунд стартует только с подарка, который реально лежит у меня.\n"
        "• Победитель выбирается честно (Provably Fair): хэш секрета виден до раунда, "
        "сам секрет — после, и любой может проверить результат.\n"
        "• Комиссия платформы — 10% с банка раунда. Платформа никому не платит из своего кармана.\n"
        "• Подарок, не попавший в раунд, всегда можно вывести обратно."
    )


def text_help(owner):
    return SEP.join([text_start(owner), text_deposit(owner), text_withdraw(), text_rules()])


def reply_for(cmd, owner):
    """Текст ответа на команду или None, если команда нам незнакома."""
    return {"start": lambda: text_start(owner), "help": lambda: text_help(owner),
            "deposit": lambda: text_deposit(owner), "withdraw": text_withdraw,
            "rules": text_rules}.get(cmd, lambda: None)()
